def audit_execution_error(reason):
    """Machine failure codes are not assertions that the answer is false."""
    return reason in {"deadline", "cancelled"} or bool(re.fullmatch(r"[a-z]+(?:_[a-z]+)+", reason))


def blocks(draft):
    return [p for s in draft.sections for p in s.paragraphs]


def validate_atom_requirement(atom, anchor, offered, sources, criteria, policy):
    """A 'complete' audit must meet its own declared evidence requirement.

    This is validation feedback to the existing bounded structured correction,
    never a local relabelling of an atom or a fabricated acceptance verdict.
    """
    from ..storage.evidence import source_threshold

    direct = [s for s in atom.supports if s.direct]
    original = [sources[offered[s.passage_id]["source_alias"]] for s in direct]
    if atom.purpose == "explanation":
        passed = ordinary_explanation(anchor, atom.purpose) and any(s["identity"] for s in original)
    else:
        primary = any(s.primary_for_claim and source["identity"] for s, source in zip(direct, original))
        passed = any(source_threshold(criteria[q], original, primary, policy) for q in atom.criterion_ids)
    if not passed:
        raise ValueError(
            f"Audit inconsistency for {anchor[:100]!r}: complete=true/entailment does not meet the atom's "
            f"{atom.purpose} evidence requirement. Reassess its meaning and sources. Ordinary architecture "
            "categories/general explanations can use traceable direct documentation; original identity, "
            "product contracts and measured results still need their core evidence. Never relabel a real "
            "core fact to evade evidence: if unsupported, return incomplete/insufficient."
        )


def answer_segments(text):
    # Stable boundaries in the ORIGINAL body, not a paraphrase generated by
    # the checker. Whitespace remains in the segments so joining is lossless.
    ends = [m.end() for m in re.finditer(r"[。！？；;.!?，,]\s*|\n+", text)]
    if not ends or ends[-1] != len(text):
        ends.append(len(text))
    start = 0
    result = {}
    for end in ends:
        if end > start:
            result[f"A{len(result)}"] = {"text": text[start:end], "start_char": start, "end_char": end}
        start = end
    return result


def audited_anchor(paragraph, atom):
    segments = answer_segments(paragraph.text)
    validate_ids(atom.anchor_ids, segments)
    indexes = [list(segments).index(key) for key in atom.anchor_ids]
    if indexes != list(range(indexes[0], indexes[-1] + 1)):
        raise ValueError("Anchor IDs must be unique, ordered, contiguous body segments")
    text = "".join(segments[key]["text"] for key in atom.anchor_ids).strip()
    if atom.anchor is not None:
        if text.count(atom.anchor) != 1:
            raise ValueError(
                "Focused anchor must be an exact unique substring of its selected segments; use anchor=null to preserve their original wording"
            )
        text = atom.anchor
    if len(text) > 1000:
        raise ValueError("Split a long assertion into smaller body segments")
    return text


def audit_spans(passages):
    """Split at original boundaries under the EXISTING evidence quote cap."""
    cap = next(
        m.max_length
        for m in EvidenceCandidate.model_fields["quote"].metadata
        if getattr(m, "max_length", None) is not None
    )
    offered, aliases = {}, {}
    for pid, p in passages.items():
        aliases[pid] = []
        text = p["text"]
        start = 0
        i = 0
        while start < len(text):
            end = min(len(text), start + cap)
            if end < len(text):
                boundary = max(text.rfind("\n", start, end), text.rfind(". ", start, end))
                if boundary > start:
                    end = boundary + 1
            value = text[start:end]
            if value.strip():
                key = pid if len(text) <= cap else f"{pid}.{i}"
                offered[key] = {
                    **p,
                    "text": value,
                    "start_char": p["start_char"] + start,
                    "end_char": p["start_char"] + end,
                }
                aliases[pid].append(key)
                i += 1
            start = end
    return offered, aliases


def support_span(passage, support):
    if support.quote is None:
        return 0, len(passage["text"]), passage["text"], False
    return locate_quote(passage["text"], support.quote, 0, 0)


def draft_of(composition):
    i = 0
    sections = []
    for sec in composition.sections:
        ps = []
        for p in sec.paragraphs:
            if (
                ps
                and p.block_type == "list"
                and ps[-1].block_type == "list"
                and p.illustrative == ps[-1].illustrative
            ):
                # Adjacent list items are one content block; preserve every
                # item and source hint instead of auditing separate mini-lists.
                ps[-1].text += "\n" + p.text
                ps[-1].passage_ids = list(dict.fromkeys(ps[-1].passage_ids + p.passage_ids))
                continue
            i += 1
            ps.append(DraftBlock(**p.model_dump(), paragraph_id=f"p{i}"))
        sections.append(DraftSection(heading=sec.heading, paragraphs=ps))
    return SourceDraft(title=composition.title, sections=sections)


class SourceWorkflow:
    def __init__(self, services, graph):
        self.s, self.graph = services, graph

    def payload(self, materials):
        used = {p["source_alias"] for p in materials["passages"].values()}
        return {
            "question": self.s.request.query,
            "reader_goal": self.s.understanding.get("reader_goal"),
            "standalone_question": self.s.understanding.get("standalone_query", self.s.request.query),
            "reader_questions": self.s.understanding.get("facets", []),
            "as_of": self.s.request.as_of.isoformat() if self.s.request.as_of else None,
            "output_language": self.s.request.output_language,
            "citations_rendered_by_application": True,
            "source_policy": self.s.understanding.get("source_policy"),
            "answer_criteria": materials.get("criteria", []),
            "sources": [
                {
                    "source_id": k,
                    "title": s["title"],
                    "url": s["canonical_url"],
                    "identity_established": bool(s["identity"]),
                    "source_identity": {
                        k: s["identity"][k]
                        for k in ["publisher_name", "basis", "identity_scope"]
                        if k in s["identity"]
                    }
                    if s["identity"]
                    else None,
                    "notes": s["notes"],
                    "material_roles": s.get("material_roles", []),
                    "firsthand_criterion_ids": s.get("firsthand_criterion_ids", []),
                }
                for k, s in materials["sources"].items()
                if k in used
            ],
            "passages": [
                {
                    "passage_id": k,
                    "source_id": p["source_alias"],
                    "text": p["text"],
                    "table_header": p["table_header"],
                }
                for k, p in materials["passages"].items()
            ],
        }

    async def material(self, state):
        notes = await SourceNotes(self.s).index()
        bysource = {}
        for note in notes:
            entry = bysource.setdefault(
                note["source_id"],
                {
                    "passages": {},
                    "notes": [],
                    "material_roles": [],
                    "identity": None,
                    "identity_claim": None,
                    "firsthand_criterion_ids": [],
                },
            )
            entry["material_roles"] = sorted(
                set(entry["material_roles"] + [note.get("material_role", "original")])
            )
            entry["firsthand_criterion_ids"] = sorted(
                set(entry["firsthand_criterion_ids"] + note.get("firsthand_criterion_ids", []))
            )
            source = await self.s.evidence.get_source(note["source_id"])
            if source["content_sha256"] != note["source_hash"]:
                raise ValueError("Source note hash differs from immutable source")
            if note["identity"]:
                entry.update(identity=note["identity"], identity_claim=note["identity_claim"])
            if note["notes"] not in entry["notes"]:
                entry["notes"].append(note["notes"])
            for p in note["passages"]:
                old = entry["passages"].setdefault(p["passage_id"], {**p, "criterion_ids": []})
                old["criterion_ids"] = sorted(set(old["criterion_ids"] + note["criterion_ids"]))
        if self.s.config.get("adaptive_research_workflow_version"):
            await self.add_bibliography(bysource)
        materials = {
            "sources": {},
            "passages": {},
            "criteria": [
                {
                    "criterion_id": c.criterion_id,
                    "question": c.description,
                    "kind": c.kind,
                    "required": c.required,
                }
                for c in self.graph.all_criteria(state).values()
            ],
        }
        ordered = sorted(bysource, key=lambda sid: (not bool(bysource[sid]["firsthand_criterion_ids"]), sid))
        queues = []
        for i, sid in enumerate(ordered):
            source = await self.s.evidence.get_source(sid)
            item = bysource[sid]
            for passage in item["passages"].values():
                if source["content_text"][passage["start_char"] : passage["end_char"]] != passage["text"]:
                    raise ValueError("Source note passage differs from immutable source")
            alias = f"S{i}"
            # Keep the full immutable original privately for deterministic span checks.
            materials["sources"][alias] = {
                **source,
                "identity": item["identity"],
                "identity_claim": item["identity_claim"],
                "notes": "\n".join(item["notes"]),
                "material_roles": item["material_roles"],
                "firsthand_criterion_ids": item["firsthand_criterion_ids"],
            }
            queues.append([{**p, "source_alias": alias} for p in item["passages"].values()])
        # Admit one complete passage per source in each pass, so the first source
        # cannot consume the entire writer context. No mid-passage truncation.
        index = 0
        while any(queues):
            for queue in queues:
                if not queue:
                    continue
                p = queue.pop(0)
                alias = f"P{index}"
                index += 1
                materials["passages"][alias] = p
                try:
                    self.s.llm.build("writer", self.payload(materials), SourceComposition)
                except Stopped as error:
                    if error.code != "input_budget_exceeded":
                        raise
                    del materials["passages"][alias]
                await asyncio.sleep(0)
        used = {p["source_alias"] for p in materials["passages"].values()}
        materials["sources"] = {k: s for k, s in materials["sources"].items() if k in used}
        return materials

    async def add_bibliography(self, bysource):
        """Retain already captured author/date evidence alongside work content.

        Reading a full paper does not mean its separately captured publication
        record was selected by the reader. Do not make the writer rediscover it.
        """
        from .publication_identity import established_identity, publication_record
        from .documents import same_work, work_identity

        candidates = set(bysource)
        index = await self.s.evidence.source_index()
        read_documents = [
            s.get("metadata", {}).get("document") or work_identity(s["canonical_url"])
            for s in index
            if s["id"] in bysource
        ]
        # A full-text page can establish its own identity while its separate
        # publication record holds the original date. Include observed records
        # of that same work even when the identity proof points to the full text.
        for source in index:
            document = source.get("metadata", {}).get("document") or work_identity(source["canonical_url"])
            if document["representation"] == "abstract" and any(
                same_work(document, read) for read in read_documents
            ):
                candidates.add(source["id"])
        for item in bysource.values():
            identity = item.get("identity") or {}
            if identity.get("support_source_id"):
                candidates.add(identity["support_source_id"])
        for sid in sorted(candidates):
            source = await self.s.evidence.get_source(sid)
            proof = await established_identity(self.s, sid)
            if not proof:
                continue
            text = source["content_text"]
            ranges = []
            record = publication_record(source)
            if record and record["document"]["representation"] == "abstract":
                # Exact publication header, including original submission date.
                ranges.append((0, min(len(text), self.s.config["fetch"]["chunk_chars"])))
            for field in source.get("metadata", {}).get("bibliographic_fields", []):
                value = field.get("value", "")
                start = text.find(value) if value else -1
                if start >= 0:
                    ranges.append((start, start + len(value)))
            if not ranges:
                continue
            entry = bysource.setdefault(
                sid,
                {
                    "passages": {},
                    "notes": ["Captured bibliographic record for attribution and publication date."],
                    "material_roles": ["original"],
                    "identity": proof,
                    "identity_claim": None,
                    "firsthand_criterion_ids": [],
                },
            )
            if not entry["identity"]:
                entry.update(identity=proof, identity_claim=None)
            for start, end in ranges:
                if any(p["start_char"] <= start and p["end_char"] >= end for p in entry["passages"].values()):
                    continue
                pid = stable_id("bibliographic-passage", sid, start, end)
                entry["passages"][pid] = {
                    "passage_id": pid,
                    "source_id": sid,
                    "start_char": start,
                    "end_char": end,
                    "text": text[start:end],
                    "table_header": None,
                    "criterion_ids": [],
                }

    def validate_composition(self, value, materials):
        for sec in value.sections:
            for p in sec.paragraphs:
                validate_ids(p.passage_ids, materials["passages"])

    async def write(self, state):
        await self.s.db.phase(self.s.run_id, self.s.fence, "write")
        self.s.understanding = state["understanding"]
        material = await self.material(state)
        try:
            if not material["passages"]:
                raise Stopped("no_source_material")
            value = await self.s.llm.generate(
                "write:source:v1",
                "writer",
                self.payload(material),
                SourceComposition,
                partition="finalization",
                validator=lambda v: self.validate_composition(v, material),
            )
            initial = draft_of(value).model_dump(mode="json")
            await self.s.db.commit_value(
                self.s.run_id, self.s.fence, "draft:initial:v1", "unverified_draft", initial
            )
            return {
                "source_materials": material,
                "source_draft": initial,
                "fallback_report": False,
            }
        except (Stopped, ToolFailure) as error:
            if getattr(error, "fatal", False) or error.code == "cancelled":
                raise
            await self.s.warn("source_synthesis.unavailable", reason=error.code)
            result = await self.fallback("本次研究未能完成综合回答。已获取的来源保留在研究记录中。")
            if error.code in {"budget_exhausted", "deadline"}:
                result["stop_reason"] = error.code
            return result

    async def fallback(self, message):
        # Diagnostics are not a substitute answer. Keep fetched materials in
        # storage, but do not dump all excerpts into the chat's default body.
        draft = NarrativeDraft(
            schema_version=3,
            title=self.s.request.query,
            sections=[],
            limitations=[message],
            unresolved_questions=[self.s.request.query],
            quality_status="not_checked",
        )
        return {
            "report_draft": draft.model_dump(mode="json"),
            "fallback_report": True,
            "report_partial": True,
            "report_coverage": 0.0,
        }

    def audit_payload(self, group, state):
        material = state["source_materials"]
        draft = SourceDraft.model_validate(state["source_draft"])
        chosen = {pid for p in group for pid in p.passage_ids}
        related = {cid for pid in chosen for cid in material["passages"][pid]["criterion_ids"]}
        required = set(chosen)
        cited_sources = {material["passages"][pid]["source_alias"] for pid in chosen}
        # Writer hints are fallible: include related context from BOTH the
        # same work and other sources, including competing accounts.
        chosen |= {
            pid
            for pid, p in material["passages"].items()
            if related.intersection(p["criterion_ids"])
            or (not related and p["source_alias"] in cited_sources)
        }
        ps = {pid: p for pid, p in material["passages"].items() if pid in chosen}
        ss = {p["source_alias"] for p in ps.values()}
        qa = {f"Q{i}": c for i, c in enumerate(self.graph.all_criteria(state))}
        criteria = self.graph.all_criteria(state)
        group_ids = {p.paragraph_id for p in group}
        neighbors = {}
        for section in draft.sections:
            for i, paragraph in enumerate(section.paragraphs):
                if paragraph.paragraph_id not in group_ids:
                    continue
                for adjacent in section.paragraphs[max(0, i - 1) : i + 2]:
                    if adjacent.paragraph_id not in group_ids:
                        neighbors[adjacent.paragraph_id] = {
                            "paragraph_id": adjacent.paragraph_id,
                            "text": adjacent.text,
                            "illustrative": adjacent.illustrative,
                            "block_type": adjacent.block_type,
                            "heading": section.heading,
                        }
        payload = {
            "report_title": draft.title,
            "surrounding_answer_context": list(neighbors.values()),
            "verify_title": any(p.paragraph_id == blocks(draft)[0].paragraph_id for p in group),
            "paragraphs": [
                {
                    **p.model_dump(exclude={"text"}),
                    "segments": [
                        {"anchor_id": k, "text": v["text"]} for k, v in answer_segments(p.text).items()
                    ],
                    "heading": next(
                        sec.heading
                        for sec in draft.sections
                        if p.paragraph_id in [x.paragraph_id for x in sec.paragraphs]
                    ),
                }
                for p in group
            ],
            "sources": [
                {
                    "source_id": sid,
                    "title": material["sources"][sid]["title"],
                    "url": material["sources"][sid]["canonical_url"],
                    "identity_established": bool(material["sources"][sid]["identity"]),
                    "source_identity": {
                        k: material["sources"][sid]["identity"][k]
                        for k in ["publisher_name", "basis", "identity_scope"]
                        if k in material["sources"][sid]["identity"]
                    }
                    if material["sources"][sid]["identity"]
                    else None,
                }
                for sid in sorted(ss)
            ],
            "passages": [
                {
                    "passage_id": pid,
                    "source_id": p["source_alias"],
                    "text": p["text"],
                    "table_header": p["table_header"],
                }
                for pid, p in ps.items()
            ],
            "criteria": [
                {"criterion_id": q, "description": criteria[c].description, "kind": criteria[c].kind}
                for q, c in qa.items()
            ],
        }

        def wire(selected):
            offered, aliases = audit_spans(selected)
            built = {
                **payload,
                "passages": [
                    {
                        "passage_id": pid,
                        "source_id": p["source_alias"],
                        "text": p["text"],
                        "table_header": p["table_header"],
                    }
                    for pid, p in offered.items()
                ],
                "paragraphs": [
                    {**p, "passage_ids": [span for pid in p["passage_ids"] for span in aliases[pid]]}
                    for p in payload["paragraphs"]
                ],
            }
            return built, offered

        built, offered = wire(ps)
        try:
            self.s.llm.build("report_verifier", built, SourceBatchAudit)
        except Stopped as error:
            if error.code != "input_budget_exceeded":
                raise
            selected = {pid: p for pid, p in ps.items() if pid in required}
            self.s.llm.build("report_verifier", wire(selected)[0], SourceBatchAudit)
            # Round-robin source context avoids filling all remaining room
            # with the first publisher. Other draft hints come first within
            # a source; no new numeric packet cap or source-count threshold.
            draft_hints = {pid for p in blocks(draft) for pid in p.passage_ids}
            queues = {}
            for pid in sorted(ps, key=lambda pid: (pid not in draft_hints, list(ps).index(pid))):
                if pid not in selected:
                    queues.setdefault(ps[pid]["source_alias"], []).append(pid)
            while any(queues.values()):
                for queue in queues.values():
                    if not queue:
                        continue
                    pid = queue.pop(0)
                    trial = {**selected, pid: ps[pid]}
                    try:
                        self.s.llm.build("report_verifier", wire(trial)[0], SourceBatchAudit)
                        selected = trial
                    except Stopped as nested:
                        if nested.code != "input_budget_exceeded":
                            raise
            built, offered = wire(selected)
        return built, offered, qa

    def estimated_audit_output(self, group):
        # Budget actual anchors and the current schema overhead per clause,
        # instead of assuming four arbitrarily dense blocks fit 2400 tokens.
        result = {"paragraphs": []}
        for p in group:
            clauses = [s.strip() for s in re.split(r"(?<=[。！？；;.!?，,])\s*|\n+", p.text) if s.strip()]
            result["paragraphs"].append(
                {
                    "paragraph_id": p.paragraph_id,
                    "atoms": [
                        {
                            "anchor_ids": ["A0"],
                            "anchor": None,
                            "kind": "inference",
                            "purpose": "core_fact",
                            "verdict": "entailment",
                            "supports": [
                                {
                                    "passage_id": f"P{i}.0",
                                    "quote": None,
                                    "primary_for_claim": True,
                                    "direct": True,
                                }
                                for i in range(1)
                            ],
                            "criterion_ids": ["Q0"],
                            "answered_criterion_ids": ["Q0"],
                        }
                        for text in clauses
                    ],
                    "discourse_ids": [],
                    "complete": True,
                    "headings_supported": True,
                    "unsupported_text": [],
                    "explanation": "The statements and their qualifications are supported by the original passages.",
                }
            )
        return len(
            tiktoken.get_encoding(self.s.config["tokenizer"]).encode(canonical(result), disallowed_special=())
        )

    def audit_packets(self, ps, state):
        group = []
        for p in ps:
            if len(group) >= self.s.config["model"]["roles"]["report_verifier"]["max_paragraphs"]:
                yield group
                group = []
            if (
                group
                and self.estimated_audit_output(group + [p])
                > self.s.config["model"]["roles"]["report_verifier"]["max_output"]
            ):
                yield group
                group = []
            try:
                self.s.llm.build(
                    "report_verifier", self.audit_payload(group + [p], state)[0], SourceBatchAudit
                )
            except Stopped as error:
                if error.code != "input_budget_exceeded":
                    raise
                if group:
                    yield group
                    group = []
            group.append(p)
        if group:
            yield group

    async def audit(self, group, state, key, is_recheck=False):
        payload, offered, qa = self.audit_payload(group, state)
        pmap = {p.paragraph_id: p for p in group}
        material = state["source_materials"]
        criteria = {q: self.graph.all_criteria(state)[cid] for q, cid in qa.items()}

        def validate(value):
            if len(value.paragraphs) != len(pmap) or {p.paragraph_id for p in value.paragraphs} != set(pmap):
                raise ValueError("Return exactly one audit for every requested block")
            for p in value.paragraphs:
                if p.complete and not p.atoms:
                    raise ValueError("Complete substantive blocks need audited atoms")
                segment_map = answer_segments(pmap[p.paragraph_id].text)
                validate_ids(p.discourse_ids, segment_map)
                covered = set(p.discourse_ids)
                for a in p.atoms:
                    anchor = audited_anchor(pmap[p.paragraph_id], a)
                    if a.purpose == "explanation" and not ordinary_explanation(anchor, a.purpose):
                        raise ValueError(
                            "Original identity/design, official contracts and empirical results are core_fact, not ordinary explanation"
                        )
                    anchor_span(pmap[p.paragraph_id], type("Anchor", (), {"anchor": anchor})())
                    covered.update(a.anchor_ids)
                    validate_ids(a.criterion_ids, qa)
                    validate_ids(a.answered_criterion_ids, a.criterion_ids)
                    if a.verdict == "entailment" and not a.supports:
                        raise ValueError(
                            "An accepted atom needs original source premises; pure discourse needs no atom"
                        )
                    for support in a.supports:
                        validate_ids([support.passage_id], offered)
                        if not support_span(offered[support.passage_id], support):
                            raise ValueError(
                                "Support quote must match one exact contiguous original passage; no ellipses or paraphrase"
                            )
                        source = material["sources"][offered[support.passage_id]["source_alias"]]
                        if support.primary_for_claim and not source["identity"]:
                            raise ValueError("An unidentified source cannot be primary for a claim")
                    if p.complete and a.verdict == "entailment":
                        validate_atom_requirement(
                            a,
                            anchor,
                            offered,
                            material["sources"],
                            criteria,
                            state["understanding"]["source_policy"],
                        )
                if p.complete and covered != set(segment_map):
                    raise ValueError(
                        "Every original body segment must be accounted for by an atom or discourse_ids"
                    )

        try:
            value = await self.s.llm.generate(
                key,
                "report_verifier",
                payload,
                SourceBatchAudit,
                partition="finalization",
                is_recheck=is_recheck,
                validator=validate,
            )
        except ToolFailure as error:
            if error.code != "audit_output_truncated" or len(group) == 1:
                raise
            good, bad, heads = {}, {}, []
            middle = len(group) // 2
            for label, part in [("left", group[:middle]), ("right", group[middle:])]:
                try:
                    g, b, h = await self.audit(part, state, key + ":" + label, is_recheck)
                    good.update(g)
                    bad.update(b)
                    heads += h
                except (Stopped, ToolFailure) as nested:
                    if getattr(nested, "fatal", False) or nested.code == "cancelled":
                        raise
                    bad.update({p.paragraph_id: nested.code for p in part})
            return good, bad, heads
        accepted, errors, headings = {}, {}, []
        tasks = [ResearchTask.model_validate(t) for t in state["plan_history"][0]["tasks"]]
        candidates = {}
        for item in value.paragraphs:
            p = pmap[item.paragraph_id]
            if not item.headings_supported:
                headings.append(p.paragraph_id)
            if (
                not item.complete
                or item.unsupported_text
                or any(a.verdict != "entailment" for a in item.atoms)
            ):
                errors[p.paragraph_id] = item.explanation + " " + str(item.unsupported_text)
                continue
            assertions = []
            answered = set()
            for i, atom in enumerate(item.atoms):
                anchor = audited_anchor(p, atom)
                cids, eids = set(), set()
                mapped = [qa[q] for q in atom.criterion_ids]
                for support in atom.supports:
                    passage = offered[support.passage_id]
                    source = material["sources"][passage["source_alias"]]
                    start, end, quote, _ = support_span(passage, support)
                    start += passage["start_char"]
                    end += passage["start_char"]
                    candidate = EvidenceCandidate(
                        source_id=source["id"],
                        chunk_id=passage["passage_id"],
                        quote=quote,
                        start_char=start,
                        end_char=end,
                        claim_text=anchor,
                        relation="supports",
                        criterion_ids=mapped,
                        temporal_scope=None,
                        directness="direct" if support.direct else "indirect",
                    )
                    for task in tasks:
                        ids = sorted(set(mapped) & {c.criterion_id for c in task.success_criteria})
                        if not ids:
                            continue
                        verdict = EvidenceVerdict(
                            candidate_index=0,
                            relation="supports",
                            direct=support.direct,
                            primary_for_claim=support.primary_for_claim,
                            criterion_ids=ids,
                            explanation="Independent final-answer audit against original passage.",
                        )
                        await self.s.evidence.persist(
                            task,
                            [(candidate.model_copy(update={"criterion_ids": ids}), verdict)],
                            primary_provenance=source["identity"],
                            identity_claim=source["identity_claim"],
                            assertion_purpose=atom.purpose,
                        )
                    cids.add(stable_id("claim", self.s.run_id, normalize(anchor), ""))
                    eids.add(stable_id("evidence", source["id"], start, end))
                assertions.append(
                    NarrativeAssertion(
                        statement_id=f"{p.paragraph_id}:a{i}",
                        text=anchor,
                        anchor=anchor,
                        kind=atom.kind,
                        claim_ids=sorted(cids),
                        evidence_ids=sorted(eids),
                    )
                )
                answered.update(qa[q] for q in atom.answered_criterion_ids)
            candidates[p.paragraph_id] = (
                NarrativeParagraph(
                    **{
                        **p.model_dump(exclude={"passage_ids"}),
                        "illustrative": p.illustrative or all(a.kind == "example" for a in item.atoms),
                    },
                    assertions=assertions,
                ),
                answered,
            )
        await self.s.evidence.assessments(
            list(self.graph.all_criteria(state).values()),
            state["understanding"]["source_policy"],
            state["batch_no"],
        )
        bundle = await self.s.evidence.bundle()
        for pid, (p, answered) in candidates.items():
            try:
                for a in p.assertions:
                    validate_statement(a, bundle)
                accepted[pid] = (p, answered)
            except ValueError as error:
                errors[pid] = f"{error}: {a.anchor}"
        return accepted, errors, headings

    async def validate(self, state):
        await self.s.ops.close_finalization_stage("writer")
        if state.get("fallback_report"):
            return {}
        await self.s.db.phase(self.s.run_id, self.s.fence, "validate_report")
        draft = SourceDraft.model_validate(state["source_draft"])
        accepted, errors, heads = {}, {}, []
        stop_reason = None
        for group in self.audit_packets(blocks(draft), state):
            try:
                g, b, h = await self.audit(
                    group, state, "source-audit:" + digest([p.model_dump() for p in group])
                )
                accepted.update(
                    {
                        pid: {"paragraph": p.model_dump(mode="json"), "answers": sorted(a)}
                        for pid, (p, a) in g.items()
                    }
                )
                errors.update(b)
                heads += h
            except (Stopped, ToolFailure, ValueError) as error:
                if getattr(error, "fatal", False) or getattr(error, "code", None) == "cancelled":
                    raise
                errors.update({p.paragraph_id: getattr(error, "code", str(error)) for p in group})
                if getattr(error, "code", None) in {"budget_exhausted", "deadline"}:
                    stop_reason = error.code
                    break
        await self.s.ops.close_finalization_stage("report_verifier")
        return {
            "initial_audit": {"accepted": accepted, "errors": errors, "headings": heads},
            **({"stop_reason": stop_reason} if stop_reason else {}),
        }

    async def quality(self, state):
        if state.get("fallback_report"):
            return {}
        await self.s.db.phase(self.s.run_id, self.s.fence, "quality")
        draft = SourceDraft.model_validate(state["source_draft"])
        initial = state["initial_audit"]
        accepted = {
            pid: (NarrativeParagraph.model_validate(v["paragraph"]), set(v["answers"]))
            for pid, v in initial["accepted"].items()
        }
        if state.get("stop_reason") in {"budget_exhausted", "deadline"}:
            return {
                **await self.finish(draft, accepted, state, "not_checked", True, initial["headings"]),
                "stop_reason": state["stop_reason"],
            }
        review_payload = {
            "question": self.s.request.query,
            "reader_goal": state["understanding"].get("reader_goal"),
            "title": draft.title,
            "sections": [
                {"heading": s.heading, "paragraph_ids": [p.paragraph_id for p in s.paragraphs]}
                for s in draft.sections
            ],
            "paragraphs": [p.model_dump(exclude={"passage_ids"}) for p in blocks(draft)],
            "citations_rendered_by_application": True,
        }
        try:
            review = await self.s.llm.generate(
                "quality:source:v1",
                "quality",
                review_payload,
                QualityReview,
                partition="finalization",
                validator=lambda v: validate_ids(
                    [pid for i in v.issues for pid in i.paragraph_ids],
                    [p.paragraph_id for p in blocks(draft)],
                ),
            )
        except (Stopped, ToolFailure) as error:
            if getattr(error, "fatal", False) or error.code == "cancelled":
                raise
            return {
                **await self.finish(draft, accepted, state, "not_checked", True, initial["headings"]),
                **({"stop_reason": error.code} if error.code in {"budget_exhausted", "deadline"} else {}),
            }
        await self.s.ops.close_finalization_stage("quality")
        feedback = [{"feedback_id": f"Q{i}", **q.model_dump()} for i, q in enumerate(review.issues)]
        feedback += [
            {
                "feedback_id": f"F{i}",
                "paragraph_ids": [pid],
                "problem": reason,
                "feedback_kind": "audit_execution" if audit_execution_error(reason) else "fact",
                "suggestion": (
                    "The verifier failed to produce a usable assessment. This does not show a defect in the prose or SDK example. Preserve its meaning and let the existing recheck assess it; do not invent a factual objection from this error."
                    if audit_execution_error(reason)
                    else "Fix unsupported content while preserving the explanation."
                ),
            }
            for i, (pid, reason) in enumerate(initial["errors"].items())
        ]
        feedback += [
            {
                "feedback_id": f"H{i}",
                "paragraph_ids": [pid],
                "problem": "Unsupported factual heading/title",
                "suggestion": "Use a supported heading.",
            }
            for i, pid in enumerate(initial["headings"])
        ]
        if not feedback:
            return {
                **await self.finish(draft, accepted, state, "passed", False, []),
                "quality_review": review.model_dump(),
            }
        payload = {
            **self.payload(state["source_materials"]),
            "draft": draft.model_dump(),
            "feedback": feedback,
        }

        def expand_revision(value):
            original = {p.paragraph_id: p for p in blocks(draft)}
            reused = []
            sections = []
            for sec in value.sections:
                content = []
                for item in sec.paragraphs:
                    if item.reuse_paragraph_id:
                        validate_ids([item.reuse_paragraph_id], original)
                        if item.reuse_paragraph_id in reused:
                            raise ValueError("An unchanged block may be reused only once")
                        reused.append(item.reuse_paragraph_id)
                        content.append(original[item.reuse_paragraph_id].model_dump(exclude={"paragraph_id"}))
                    else:
                        content.append(item.replacement.model_dump())
                sections.append(SourceSection(heading=sec.heading, paragraphs=content))
            return SourceComposition(title=value.title, sections=sections)

        def validate(value):
            self.validate_composition(expand_revision(value), state["source_materials"])
            validate_ids(value.addressed_feedback_ids, [f["feedback_id"] for f in feedback])
            validate_ids(
                [i.feedback_id for i in value.remaining_issues], [f["feedback_id"] for f in feedback]
            )

        try:
            revision = await self.s.llm.generate(
                "editor:source:v1",
                "editor",
                payload,
                SourceRevision,
                partition="finalization",
                validator=validate,
            )
        except (Stopped, ToolFailure) as error:
            if getattr(error, "fatal", False) or error.code == "cancelled":
                raise
            return {
                **await self.finish(draft, accepted, state, "issues_remaining", True, initial["headings"]),
                "quality_review": review.model_dump(),
                **({"stop_reason": error.code} if error.code in {"budget_exhausted", "deadline"} else {}),
            }
        revised = draft_of(expand_revision(revision))
        await self.s.db.commit_value(
            self.s.run_id,
            self.s.fence,
            "draft:edited:v1",
            "unverified_draft",
            revised.model_dump(mode="json"),
        )
        prior = {
            block_signature(p): (sec.heading, accepted[p.paragraph_id])
            for sec in draft.sections
            for p in sec.paragraphs
            if p.paragraph_id in accepted and p.paragraph_id not in initial["headings"]
        }
        good, pending, reused = {}, [], set()
        for si, sec in enumerate(revised.sections):
            for pi, p in enumerate(sec.paragraphs):
                old = prior.get(block_signature(p))
                if (
                    old
                    and old[1][0].paragraph_id not in reused
                    and not (
                        pi == 0 and (old[0] != sec.heading or (si == 0 and revised.title != draft.title))
                    )
                ):
                    pid = old[1][0].paragraph_id
                    sec.paragraphs[pi] = p.model_copy(update={"paragraph_id": pid})
                    good[pid] = old[1]
                    reused.add(pid)
                else:
                    p = p.model_copy(update={"paragraph_id": "edited-" + p.paragraph_id})
                    sec.paragraphs[pi] = p
                    pending.append(p)
        old_places = {
            p.paragraph_id: (block_signature(p), si, pi, sec.heading)
            for si, sec in enumerate(draft.sections)
            for pi, p in enumerate(sec.paragraphs)
        }
        new_places = {
            (block_signature(p), si, pi, sec.heading)
            for si, sec in enumerate(revised.sections)
            for pi, p in enumerate(sec.paragraphs)
        }
        failed = bool(revision.remaining_issues) or any(
            not issue.paragraph_ids or all(old_places[pid] in new_places for pid in issue.paragraph_ids)
            for issue in review.issues
        )
        heads = []
        recheck_errors = {}
        stop_reason = None
        audit_state = {**state, "source_draft": revised.model_dump(mode="json")}
        for group in self.audit_packets(pending, audit_state):
            try:
                g, b, h = await self.audit(
                    group, audit_state, "source-recheck:" + digest([p.model_dump() for p in group]), True
                )
                good.update(g)
                recheck_errors.update(b)
                failed |= bool(b or h)
                heads += h
            except (Stopped, ToolFailure, ValueError) as error:
                if getattr(error, "fatal", False) or getattr(error, "code", None) == "cancelled":
                    raise
                failed = True
                recheck_errors.update({p.paragraph_id: getattr(error, "code", str(error)) for p in group})
                if getattr(error, "code", None) in {"budget_exhausted", "deadline"}:
                    stop_reason = error.code
                    break
        return {
            **await self.finish(
                revised, good, state, "issues_remaining" if failed else "revised", failed, heads
            ),
            "quality_review": review.model_dump(),
            **({"stop_reason": stop_reason} if stop_reason else {}),
            "editorial_revision": {
                "reused_blocks": sorted(reused),
                "rechecked_blocks": [p.paragraph_id for p in pending],
                "addressed_feedback_ids": revision.addressed_feedback_ids,
                "remaining_issues": [i.model_dump() for i in revision.remaining_issues],
                "recheck_errors": recheck_errors,
            },
        }

    async def finish(self, draft, accepted, state, quality_status, failed, headings):
        missing = [p.paragraph_id for p in blocks(draft) if p.paragraph_id not in accepted]
        if not accepted:
            return await self.fallback("本次未能形成通过核验的完整回答。原始资料保留在研究记录中。")
        final = NarrativeDraft(
            schema_version=3,
            title=self.s.request.query if headings else draft.title,
            sections=[
                NarrativeSection(
                    heading="" if any(p.paragraph_id in headings for p in sec.paragraphs) else sec.heading,
                    paragraphs=[
                        accepted[p.paragraph_id][0] for p in sec.paragraphs if p.paragraph_id in accepted
                    ],
                )
                for sec in draft.sections
            ],
            limitations=[],
            unresolved_questions=[],
            quality_status=quality_status,
            paragraph_answers={pid: sorted(a) for pid, (_, a) in accepted.items()},
        )
        final.sections = [s for s in final.sections if s.paragraphs]
        if self.s.config.get("retrieval_workflow_version") and not self.s.config.get(
            "reader_budget_workflow_version"
        ):
            # An audited sentence can be true while explaining only a small part
            # of a broad reader question. Preserve the independent reading gaps.
            readiness = await SourceNotes(self.s).assessments(list(self.graph.all_criteria(state).values()))
            ready = {r.criterion_id for r in readiness if r.status == "covered"}
            final.paragraph_answers = {
                pid: sorted(set(ids) & ready) for pid, ids in final.paragraph_answers.items()
            }
        bundle = await self.s.evidence.bundle()
        result = await NarrativeWorkflow(self.s, self.graph).coverage(
            final, {**state, "quality_failed": failed or bool(missing)}, bundle
        )
        return {**result, "quality_failed": failed or bool(missing)}
